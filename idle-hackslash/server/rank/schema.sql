-- 無限反射のランキング用の表（XSERVER の phpMyAdmin で、作ったデータベースを選んで「SQL」に貼って実行）
CREATE TABLE IF NOT EXISTS players (
  id CHAR(32) NOT NULL PRIMARY KEY,
  key_hash CHAR(64) NOT NULL,
  n VARCHAR(100) NOT NULL,
  st DOUBLE NOT NULL DEFAULT 0,
  co DOUBLE NOT NULL DEFAULT 0,
  ki DOUBLE NOT NULL DEFAULT 0,
  ev DOUBLE NOT NULL DEFAULT 0,
  rf DOUBLE NOT NULL DEFAULT 0,
  dp DOUBLE NOT NULL DEFAULT 0,
  ver VARCHAR(20) NOT NULL DEFAULT '',
  at INT NOT NULL DEFAULT 0,
  created INT NOT NULL DEFAULT 0,
  INDEX ix_st (st), INDEX ix_co (co), INDEX ix_ki (ki), INDEX ix_ev (ev), INDEX ix_rf (rf), INDEX ix_dp (dp)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS daily (
  day CHAR(10) NOT NULL,
  id CHAR(32) NOT NULL,
  n VARCHAR(100) NOT NULL,
  c INT NOT NULL DEFAULT 0,
  at INT NOT NULL DEFAULT 0,
  PRIMARY KEY (day, id),
  INDEX ix_day_c (day, c)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
